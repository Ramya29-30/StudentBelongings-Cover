import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { loginAs, watchBrowser } from './helpers';

const DASHES = /[\u2014\u2013]/;

test.describe('legal pages and launch requirements', () => {
  for (const [path, title, must] of [['/privacy', 'Privacy Policy', /No AI provider is configured/], ['/terms', 'Terms and Conditions', /not an insurer/i]] as const) {
    test(`${title}: public, accessible (WCAG 2.2 AA scan), no dashes, honest about missing operator facts`, async ({ page }) => {
      const w = watchBrowser(page);
      await page.goto(path);
      await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible();
      await expect(page.getByText(/Draft, not legal advice/)).toBeVisible();          // not presented as lawyer-reviewed
      await expect(page.getByText(/Incomplete\./)).toBeVisible();                     // operator facts are flagged, never invented
      await expect(page.locator('main')).toContainText(must);
      const text = await page.locator('body').innerText();
      expect(DASHES.test(text), 'em or en dash in page copy').toBe(false);
      const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze();
      expect(r.violations.map(v => `${v.id}: ${v.nodes.map(n => n.target.join(' ')).join(' | ')}`)).toEqual([]);
      w.assertClean();
    });
  }

  test('footer links are reachable from the login page and the signed-in portal', async ({ page }) => {
    await page.goto('/login');
    await page.getByRole('link', { name: 'Privacy Policy' }).click();
    await expect(page).toHaveURL(/\/privacy$/);
    await loginAs(page, 'student');
    await page.getByRole('navigation', { name: 'Legal' }).getByRole('link', { name: 'Terms and Conditions' }).click();
    await expect(page).toHaveURL(/\/terms$/);
    await page.getByRole('link', { name: 'Back to the application' }).click();
    await expect(page).toHaveURL(/\/student$/);
  });

  test('favicon is declared and every icon file loads as an image', async ({ page, request }) => {
    await page.goto('/login');
    const hrefs = await page.locator('link[rel~="icon"], link[rel="apple-touch-icon"]').evaluateAll(els => els.map(e => (e as HTMLLinkElement).getAttribute('href')));
    expect(hrefs.length).toBeGreaterThanOrEqual(3);
    for (const h of hrefs) {
      const r = await request.get(h!);
      expect(r.status(), h!).toBe(200);
      expect(r.headers()['content-type'], h!).toMatch(/^image\//);
    }
  });

  test('no development-tool branding in the shipped page', async ({ page }) => {
    await page.goto('/login');
    const html = (await page.content()).toLowerCase();
    for (const s of ['made with', 'built with', 'lovable', 'bolt.new', 'v0.dev', 'replit', 'generated by ai']) expect(html, s).not.toContain(s);
    await expect(page).toHaveTitle(/StudentBelongings Cover/);
  });
});

test.describe('stored XSS and privacy, observed in a real browser', () => {
  test('script and markup typed by a student are rendered as inert text', async ({ page }) => {
    const w = watchBrowser(page);
    const dialogs: string[] = [];
    page.on('dialog', d => { dialogs.push(d.message()); void d.dismiss(); });
    await loginAs(page, 'student');
    const csrf = (await (await page.request.get('/api/auth/me')).json()).csrf_token;
    const payload = '<img src=x onerror="window.__xss=1"><script>window.__xss=1</script><svg onload="window.__xss=1">';
    const claim = await (await page.request.post('/api/claims', { headers: { 'X-CSRF-Token': csrf }, data: { policy_id: 1, asset_id: 1, incident_date: '2026-01-02', incident_type: 'Theft', incident_location: payload, description: payload } })).json();
    await page.goto(`/student/claims/${claim.id}`);
    await expect(page.getByRole('heading', { level: 1 }).first()).toBeVisible();
    await expect(page.locator('main')).toContainText('<img src=x onerror');               // shown literally, as text
    expect(await page.evaluate(() => (window as unknown as { __xss?: number }).__xss)).toBeUndefined();
    expect(await page.locator('main img[src="x"], main svg[onload], main script').count()).toBe(0);
    expect(dialogs).toEqual([]);
    w.assertClean();
  });

  test('a student draft is not visible to assessors; internal notes are not shown to the claimant', async ({ page }) => {
    await loginAs(page, 'assessor');
    await page.goto('/assessor/claims');
    await page.getByRole('tab', { name: 'All claims' }).click();
    await expect(page.getByRole('link', { name: 'CLM-2026-00001' })).toBeVisible();
    await expect(page.getByText('CLM-2026-00004')).toHaveCount(0);                      // seeded Draft
    const csrf = (await (await page.request.get('/api/auth/me')).json()).csrf_token;
    const put = await page.request.put('/api/claims/1/assessment', { headers: { 'X-CSRF-Token': csrf }, data: { assessor_notes: 'INTERNAL-ONLY-NOTE' } });
    expect(put.status()).toBe(200);
    await page.getByRole('button', { name: 'Sign out' }).click();
    await loginAs(page, 'student');
    const body = await (await page.request.get('/api/claims/1')).text();
    expect(body).not.toContain('INTERNAL-ONLY-NOTE');
  });
});
