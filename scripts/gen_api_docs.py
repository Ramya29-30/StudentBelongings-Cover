"""Generates docs/API.md from the FastAPI app itself (routes, methods, request models, roles).
Run:  backend\\.venv\\Scripts\\python scripts\\gen_api_docs.py     (Windows)   or   backend/.venv/bin/python scripts/gen_api_docs.py
Roles are read from the `require_roles(...)` / `current_user` dependencies in each endpoint signature, so the table cannot drift from the code."""
import inspect
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("APP_ENV", "test")
os.environ.setdefault("DATABASE_URL", f"sqlite:///{(Path(tempfile.mkdtemp()) / 'doc.db').as_posix()}")

from fastapi.routing import APIRoute  # noqa: E402

from app.main import app  # noqa: E402
from app.routers import admin, ai, auth, claims, core, finance, policies  # noqa: E402

# Walk the routers directly (newer FastAPI wraps included routers lazily, so app.routes does not list their endpoints).
all_routes = [r for r in app.routes if isinstance(r, APIRoute)] + [r for m in (auth, core, policies, claims, finance, admin, ai) for r in m.router.routes if isinstance(r, APIRoute)]
rows = []
for r in all_routes:
    if not r.path.startswith("/api"):
        continue
    src = inspect.getsource(r.endpoint)
    roles = re.findall(r'require_roles\(([^)]*)\)', src)
    if roles:
        who = ", ".join(sorted({x.strip().strip('"\'') for g in roles for x in g.split(",") if x.strip()}))
    elif "current_user" in src:
        who = "any signed-in user"
    else:
        who = "public"
    body = ""
    for p in r.dependant.body_params:
        ann = getattr(p, "field_info", None) and getattr(p.field_info, "annotation", None)
        body = getattr(ann, "__name__", "") or "form/file"
    doc = (inspect.getdoc(r.endpoint) or "").splitlines()
    rows.append((r.path, sorted(r.methods - {"HEAD", "OPTIONS"})[0], who, body, doc[0] if doc else "", r.endpoint.__module__.split(".")[-1] if r.endpoint.__module__ != "app.main" else "auth"))

order = ["auth", "core", "policies", "claims", "finance", "admin", "ai"]
out = ["# API reference", "",
       "_Generated by `scripts/gen_api_docs.py` from the running application. Interactive docs (Swagger UI) are served at `/docs` when `APP_ENV` is not `production`._", "",
       "**Authentication.** Browser clients sign in with `POST /api/auth/login` and receive an **HttpOnly, SameSite=Strict** session cookie. Every state-changing request (POST/PUT/PATCH/DELETE) must also send the CSRF token in the `X-CSRF-Token` header (returned by `/api/auth/login` and `/api/auth/me`). Scripts may send `X-Return-Token: 1` on login to receive a bearer token instead (used by the test suite); that token is never needed by the web UI.", "",
       "**Errors.** JSON `{ \"detail\": ... }`; unexpected failures return `{ \"detail\": \"Internal server error\", \"error\": { \"code\", \"request_id\" } }` and the request id is in the `X-Request-ID` header and the server log.", "",
       "**Roles.** `student`, `assessor`, `admin`. Students only ever see their own policies, assets and claims. The role column below is derived from the code.", ""]
for mod in order:
    sel = sorted([x for x in rows if x[5] == mod], key=lambda x: (x[0], x[1]))
    if not sel:
        continue
    out += [f"## {mod}", "", "| Method | Path | Who | Request body | Summary |", "|---|---|---|---|---|"]
    out += [f"| {m} | `{p}` | {w} | {b or '-'} | {d.replace('|', '/')} |" for p, m, w, b, d, _ in sel]
    out.append("")
out.append(f"_{len(rows)} endpoints._")
(ROOT / "docs" / "API.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote docs/API.md with {len(rows)} endpoints")
